                "RELIC DENSITY", "Ratio of two log-normals → log-normal"),
        };
    }

    public static string UniversalityClasses(List<AbundanceVariable> variables)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("UNIVERSALITY CLASSES OF ABUNDANCE");
        sb.AppendLine();
        sb.AppendLine("  Class            Variables              Distribution");
        sb.AppendLine("  " + new string('-', 65));

        var classes = variables.GroupBy(v => v.UniversalityClass);
        foreach (var c in classes)
        {
            var names = string.Join(", ", c.Select(v => v.Symbol));
            var dists = c.Select(v => v.ProposedDistribution).Distinct();
            sb.AppendLine($"  {c.Key,-16} {names,-22} {dists.First()}");
        }

        sb.AppendLine();
        sb.AppendLine("  ALL THREE classes follow LOG-NORMAL distributions.");
        sb.AppendLine("  This suggests a SINGLE underlying mechanism:");
        sb.AppendLine("  MULTIPLICATIVE ACTUALIZATION CASCADES.");
        return sb.ToString();
    }

