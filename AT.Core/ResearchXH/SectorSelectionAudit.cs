        => new[] { -3, -2, -1, 0, 1, 2, 3 }.Select(n => (n, ConstraintResidualForSector(n, 16))).ToArray();

    public static bool TheConstraintPermitsEverySector()
        => ConstraintAcrossSectors().All(t => t.Residual < 1e-12);

    // ===================== 4. NO OPERATION COLLAPSES A NON-ZERO SECTOR TO ZERO =====================

    /// <summary>Negating the configuration reverses the orientation, so the label reverses its sign.</summary>
    public static double NegationLabel(FieldStrengthOriginAudit.LinkField a, int l)
        => SectorLabel(Negate(a), l);

    /// <summary>Translation along x leaves the uniform field alone, so the label is preserved.</summary>
    public static double TranslatedLabel(FieldStrengthOriginAudit.LinkField a, int l, int dx)
        => SectorLabel((x, y, z, mu) => a(Mod(x - dx, l), y, z, mu), l);

    /// <summary>Reflection in y reverses the orientation, so the label changes sign.</summary>
    public static double ReflectedLabel(FieldStrengthOriginAudit.LinkField a, int l)
        => SectorLabel((x, y, z, mu) => a(x, Mod(l - 1 - y, l), z, mu), l);

    /// <summary>(Operation, label produced from n = 1) - nothing produces zero.</summary>
    public static (string Operation, double Label)[] OperationTable(int n = 1, int l = 8)
    {
        var a = UniformSector(n, l);
        return new[]
        {
            ("identity", SectorLabel(a, l)),
            ("translate x -> x + 1", TranslatedLabel(a, l, 1)),
            ("translate x -> x + 3", TranslatedLabel(a, l, 3)),
            ("reflect y -> L - 1 - y", ReflectedLabel(a, l)),
            ("negate the configuration", NegationLabel(a, l)),
        };
    }

    public static bool NoOperationCollapsesTheSectorToZero()
        => OperationTable().All(t => Math.Abs(t.Label) > 0.5);

    public static string[] OperationsThatChangeTheLabel()
        => OperationTable().Where(t => Math.Abs(t.Label - 1.0) > 0.5).Select(t => t.Operation).ToArray();

