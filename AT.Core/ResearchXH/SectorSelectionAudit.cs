/// <summary>
/// ResearchY-E_014 - SECTOR SELECTION AUDIT.
///
/// QUESTION. What selects the flux sector label n? Known: n exists, n is quantised, n survives refinement. Unknown:
/// why n != 0? Candidates: boundary conditions, topological constraints, actualization process, initial conditions,
/// occupancy arrangement. Goal: locate the ORIGIN OF SECTOR OCCUPATION.
///
/// ANSWER: **BOUNDARY - and the audit can prove the negative, which is the stronger half. No AT operation selects the
/// sector, because there is nothing for a selection to act on.**
///
///  (1) THE LABEL IS GENERATED BY ONE OPERATION AND THE OPERATION IS AN ASSIGNMENT. Adding a single quantum of uniform
///      field - A_1 -> A_1 + (2 pi / L) y - is a legitimate change of the compact link phase, since the phase is
///      periodic even though the real field is not, and it moves the label by exactly one: 0, 1, 2, 3 from the
///      vacuum, with the field strength following E_011's 2 pi n / L series. The operation is invertible to machine
///      precision, so the sectors are one orbit under an assignment, not a family that dynamics moves between.
///
///  (2) NOTHING IN AT DEPENDS ON THE SECTOR. The occupancy's own curvature contribution is IDENTICAL in the trivial
///      and the unit sector - measured through linearity rather than asserted - and so is the update rule's electric
///      part and the clock law. Every law that could weight a sector is sector-blind, while a control shows the sector
///      itself is plainly visible. A theory with no potential for a label cannot prefer a value of it.
///
///  (3) THE CONSTRAINT PERMITS EVERY SECTOR, so it cannot select one. E_012's whole-torus residual is zero for every
///      integer n at every lattice size tested: the constraint that FORBIDS the single fluxon does not restrict the
///      uniform family at all. A selection argument from the constraint is therefore impossible in principle.
///
///  (4) NO SYMMETRY COLLAPSES A NON-ZERO SECTOR TO ZERO. The configuration space's operations are measured: translation
///      preserve the label, reflection reverses its sign (the orientation is reversed), negation reverses it too. None
///      maps a non-zero label to zero, so n = 0 is not a fixed point anything in AT prefers - which is why the
///      question "why n != 0" has the same status as "why n = 0": neither is selected.
///
///  (5) SO THE CANDIDATES SORT THEMSELVES. TOPOLOGICAL CONSTRAINTS are REFUTED - the constraint permits every sector.
///      THE ACTUALIZATION PROCESS is REFUTED - its field strength is purely electric (E_009, E_013). OCCUPANCY
///      ARRANGEMENT is REFUTED - sector-blind and scaling away (E_010, E_012). BOUNDARY CONDITIONS and INITIAL
///      CONDITIONS are both BOUNDARY, and they are the SAME origin under two names, a degeneracy recorded rather than
///      resolved: when the assignment is made is not a different mechanism from where it is made.
///
///  (6) WHAT THIS CHANGES. E_011 called the integer a sector label and E_012 constrained the allowed patterns; this
///      audit locates the occupation itself and shows the location cannot be inside AT: the label is generated by an
///      assignment, is invisible to every law, is permitted by every constraint at every value, and is collapsed to
///      zero by no symmetry. AT derives the LABEL and its quantisation; the OCCUPATION is a boundary.
/// </summary>
public static class SectorSelectionAudit
{
    public const int D = 3;
    public const int L96 = 96;

    private static int Mod(int v, int l) => ((v % l) + l) % l;

    public static double Quantum(int l) => FluxOriginAudit.FluxPerPlaquette(1, l);

    // ===================== 1. THE SECTOR LABEL AND THE ONE OPERATION THAT GENERATES IT =====================

    /// <summary>E_011's uniform sector: A_1 = (2 pi n / L) y. Reused through the label, not redefined.</summary>
    public static FieldStrengthOriginAudit.LinkField UniformSector(int n, int l)
        => (x, y, z, mu) => mu == 1 ? FluxOriginAudit.FluxPerPlaquette(n, l) * y : 0.0;

    /// <summary>One quantum of uniform field, as an additive change to the link phase.</summary>
    public static FieldStrengthOriginAudit.LinkField OneQuantum(int l) => UniformSector(1, l);

    public static FieldStrengthOriginAudit.LinkField Add(
        FieldStrengthOriginAudit.LinkField a, FieldStrengthOriginAudit.LinkField b)
        => (x, y, z, mu) => a(x, y, z, mu) + b(x, y, z, mu);

    public static FieldStrengthOriginAudit.LinkField Negate(FieldStrengthOriginAudit.LinkField a)
        => (x, y, z, mu) => -a(x, y, z, mu);

    public static FieldStrengthOriginAudit.LinkField Vacuum() => (x, y, z, mu) => 0.0;

    /// <summary>
    /// The label, read the way a measurement would read it: the uniform strength in units of the quantum, taken from
    /// the REDUCED plaquette so that the seam cell is read as the same phase as every other cell. The reduction is not
    /// decoration: without it the wrap-around cell reports the unreduced value and a uniform sector looks non-uniform.
    /// </summary>
    public static double SectorLabel(FieldStrengthOriginAudit.LinkField a, int l)
        => (-FluxExcitationAudit.Reduced(FieldStrengthOriginAudit.PlaquettePhase(a, 1, 2, 0, 0, 0, l)) / Quantum(l)) + 0.0;

    /// <summary>How far the configuration is from being uniform - zero for a uniform sector.</summary>
    public static double UniformityResidual(FieldStrengthOriginAudit.LinkField a, int l, int stride = 1)
    {
        double first = FluxExcitationAudit.Reduced(FieldStrengthOriginAudit.PlaquettePhase(a, 1, 2, 0, 0, 0, l));
        double worst = 0.0;
        for (int x = 0; x < l; x += stride)
            for (int y = 0; y < l; y += stride)
                for (int z = 0; z < l; z += stride)
                    worst = Math.Max(worst, Math.Abs(
                        FluxExcitationAudit.Reduced(FieldStrengthOriginAudit.PlaquettePhase(a, 1, 2, x, y, z, l)) - first));
        return worst;
    }

    public static int[] LatticeSizes() => new[] { 8, 16, 32, 64 };

    /// <summary>The label survives refinement: it is n at every lattice size, while the strength falls as 1/L.</summary>
    public static (int L, double Label, double Strength)[] LabelSurvivesRefinement(int n = 1)
        => LatticeSizes().Select(l =>
        {
            var a = UniformSector(n, l);
            return (l, SectorLabel(a, l), Math.Abs(FieldStrengthOriginAudit.PlaquettePhase(a, 1, 2, 0, 0, 0, l)));
        }).ToArray();

    public static bool TheLabelSurvivesRefinement()
        => LabelSurvivesRefinement().All(t => Math.Abs(t.Label - 1.0) < 1e-9);

    /// <summary>
    /// The shift is a legitimate change of a COMPACT phase: the real field at the far end is 2 pi, not 0, but the
    /// phase is the same. Measured on the phase, not on the real number.
    /// </summary>
    public static double ShiftPhasePeriodicityResidual(int l = 8)
    {
        double atFarEnd = Quantum(l) * l;       // 2 pi
        double atOrigin = 0.0;
        var far = System.Numerics.Complex.Exp(new System.Numerics.Complex(0.0, atFarEnd));
        var origin = System.Numerics.Complex.Exp(new System.Numerics.Complex(0.0, atOrigin));
        return System.Numerics.Complex.Abs(far - origin);
    }

    public static double ShiftRealPeriodicityResidual(int l = 8) => Math.Abs(Quantum(l) * l - 0.0);

    /// <summary>The shift moves the label by exactly one quantum.</summary>
    public static int ShiftMovesTheLabelByOne(int n, int l)
    {
        double before = SectorLabel(UniformSector(n, l), l);
        double after = SectorLabel(Add(UniformSector(n, l), OneQuantum(l)), l);
        return (int)Math.Round(after - before);
    }

    /// <summary>The shift is invertible: adding it and subtracting it returns the configuration.</summary>
    public static double ShiftInvertibilityResidual(int l = 8)
    {
        var a = UniformSector(3, l);
        var back = Add(Add(a, OneQuantum(l)), Negate(OneQuantum(l)));
        double worst = 0.0;
        for (int x = 0; x < l; x++)
            for (int y = 0; y < l; y++)
                for (int z = 0; z < l; z++)
                    for (int mu = 1; mu <= 3; mu++)
                        worst = Math.Max(worst, Math.Abs(back(x, y, z, mu) - a(x, y, z, mu)));
        return worst;
    }

    /// <summary>From the vacuum alone, the operation generates the family: 0, 1, 2, 3.</summary>
    public static (int Steps, double Label)[] VacuumToSectorSeries(int steps = 3)
    {
        int l = 16;
        var a = Vacuum();
        var rows = new List<(int, double)>();
        for (int k = 0; k <= steps; k++)
        {
            rows.Add((k, SectorLabel(a, l)));
            a = Add(a, OneQuantum(l));
        }
        return rows.ToArray();
    }

    public static bool OneOperationGeneratesTheFamily()
    {
        var series = VacuumToSectorSeries();
        for (int k = 0; k < series.Length; k++)
            if (Math.Abs(series[k].Label - k) > 1e-9) return false;
        return true;
    }

    // ===================== 2. NOTHING IN AT DEPENDS ON THE SECTOR =====================

    /// <summary>
    /// The occupancy's own curvature contribution, measured through linearity rather than asserted: the contribution
    /// is what the organisation adds ON TOP of the sector, so it is read as a difference of two curvatures.
    /// </summary>
    public static double OccupancyContributionToCurvature(int n, int l)
    {
        var sector = UniformSector(n, l);
        var occupancy = MagneticSectorAudit.CovariantForm(MagneticSectorAudit.DerivedCoupling());
        FieldStrengthOriginAudit.LinkField occupancyAsLink = (x, y, z, mu) => occupancy(l, x, y, z, mu);
        double worst = 0.0;
        for (int x = 0; x < l; x++)
            for (int y = 0; y < l; y++)
                for (int z = 0; z < l; z++)
                    foreach (var (mu, nu) in FieldStrengthOriginAudit.Orientations())
                    {
                        double withSector = FieldStrengthOriginAudit.PlaquettePhase(
                            Add(occupancyAsLink, sector), mu, nu, x, y, z, l);
                        double sectorOnly = FieldStrengthOriginAudit.PlaquettePhase(sector, mu, nu, x, y, z, l);
                        worst = Math.Max(worst, Math.Abs(withSector - sectorOnly));
                    }
        return worst;
    }

