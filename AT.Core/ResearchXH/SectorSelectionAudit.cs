            sb.AppendLine($"     -> {status}: {basis}");
        }
        sb.AppendLine();
        sb.AppendLine("6. WHAT IS KNOWN AND WHAT IS NOT");
        foreach (var (requirement, status) in RequirementCheck())
            sb.AppendLine($"   {requirement,-32} : {status}");
        return sb.ToString();
    }

    public static string OutputVerdict()
    {
        var sb = new StringBuilder();
        sb.AppendLine("7. VERDICT");
        sb.AppendLine(Verdict());
        sb.AppendLine($"   the origin of sector occupation : {TheOriginOfSectorOccupation()}");
        sb.AppendLine($"   refuted                         : {string.Join(", ", RefutedCandidates())}");
        sb.AppendLine($"   boundary                        : {string.Join(", ", BoundaryCandidates())}");
        sb.AppendLine();
        sb.AppendLine(WhereItStands());
        sb.AppendLine(WhereItStandsTail());
        return sb.ToString();
    }
