                GpsCorrectionOrigin.ClockRate(D, 1.4), GpsCorrectionOrigin.ClockRate(D, 1.4)),
        }.Select(r => (r.Item1, r.Item2, r.Item3, Math.Abs(r.Item3 - r.Item2))).ToArray();

    public static double SectorBlindnessResidual() => SectorBlindnessTable().Max(r => r.Difference);

    public static bool EveryATLawIsSectorBlind() => SectorBlindnessResidual() < 1e-12;

    /// <summary>The control: the sector itself is plainly visible to a curvature measurement.</summary>
    public static double Control_TheSectorIsVisible()
        => Math.Abs(SectorLabel(UniformSector(1, 8), 8) - SectorLabel(Vacuum(), 8));

    // ===================== 3. THE CONSTRAINT PERMITS EVERY SECTOR =====================

    /// <summary>E_012's whole-torus residual, for the uniform sector n: a whole number of turns every time.</summary>
    public static double ConstraintResidualForSector(int n, int l)
        => FluxExcitationAudit.WholeTorusConstraintResidual(
            Enumerable.Repeat(FluxOriginAudit.FluxPerPlaquette(n, l), l).ToArray());

