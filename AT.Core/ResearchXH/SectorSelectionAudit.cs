    public static (string Law, double AtSectorZero, double AtSectorOne, double Difference)[] SectorBlindnessTable()
        => new[]
        {
            ("occupancy curvature contribution",
                OccupancyContributionToCurvature(0, 8), OccupancyContributionToCurvature(1, 8)),
            ("update rule, time-like part",
                CouplingFunctionAudit.DerivedSectorSplit().Electric,
