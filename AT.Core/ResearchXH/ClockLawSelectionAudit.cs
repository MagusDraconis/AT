    /// <summary>The clock rate of a corpus law.</summary>
    public static double Rate(ClockLaw law, double x) => ClockLawUniquenessAudit.Rate(law, x);

    /// <summary>1 + z of a corpus law.</summary>
    public static double OnePlusZ(ClockLaw law, double x) => ClockLawUniquenessAudit.OnePlusZ(law, x);

    // ===================== 2. THE WITNESSES =====================

    /// <summary>
    /// THE MESH INTERPOLANT: a VIABLE law that agrees with exp(2x) at EVERY point of a mesh of spacing delta and
    /// differs between the points, so multiplicativity tested where an observer can test it - the mesh - is satisfied
    /// exactly while the law is not the exponential. The modulation is sin^2(pi x / delta), which vanishes at every
    /// mesh point and has zero slope at the vacuum, so the pinned data survive the interpolation.
    ///
    /// MONOTONICITY BOUNDS THE MODULATION, and the audit reports the bound rather than choosing a small number: the
    /// derivative carries a term beta*pi/delta, so monotonicity needs beta &lt; 2*delta/pi - i.e. THE SELECTION IS ONLY
    /// AS STRONG AS THE OPERATIONAL RESOLUTION IT IS TESTED AT.
    /// </summary>
    public static ClockLaw MeshInterpolant(double delta, double beta = 0.0)
    {
        double amplitude = beta > 0.0 ? beta : 0.999 * 2.0 * delta / Math.PI;
        return new ClockLaw($"mesh interpolant (delta = {delta:G4})",
            x => Math.Exp(2.0 * x) * (1.0 + amplitude * Math.Pow(Math.Sin(Math.PI * x / delta), 2.0)),
            "exp(2x) on the mesh, modulated between the points");
    }

    /// <summary>
    /// THE SUBGROUP WITNESS: the exponent A(m + n*sqrt(2)) = 2m + lambda*n is ADDITIVE on the subgroup generated by 1
    /// and sqrt(2) - so F = exp(A) is MULTIPLICATIVE there, carries F(0) = 1 exactly, and takes any value wanted at
    /// sqrt(2). This is the constraint imposed on the potentials an observer can PREPARE AND COMPARE, which is a
    /// finitely generated set rather than a continuum.
    ///
    /// The audit does NOT claim this is a physical law: it claims that the constraint, imposed on that domain, does
    /// not determine the law, and it measures the consequence - the values outside the subgroup are free, and the
    /// values inside it are UNBOUNDED in every neighbourhood of the vacuum unless lambda = 2*sqrt(2).
    /// </summary>
    public static double SubgroupExponent(double lambda, int m, int n) => 2.0 * m + lambda * n;

    /// <summary>
    /// THE WITNESS'S OWN UNBOUNDEDNESS, MEASURED: the Pell pairs (m, n) with m/n approaching sqrt(2) give subgroup
    /// elements x = m - n*sqrt(2) approaching the vacuum, and the exponent there is A = 2m - lambda*n, which stays
    /// O(n) unless lambda = 2*sqrt(2). So the law is unbounded near the vacuum for every other lambda - and the ONLY
    /// lambda that keeps it bounded, monotone and continuous is the one that makes the exponent linear.
    /// </summary>
    public static (int N, double X, double Exponent, double F)[] SubgroupApproach(double lambda)
    {
        var rows = new List<(int, double, double, double)>();
        foreach (int n in new[] { 2, 5, 12, 29, 70, 169, 408, 985 })
        {
            int m = (int)Math.Round(n * Math.Sqrt(2.0));
            double x = m - n * Math.Sqrt(2.0);                  // the subgroup element nearest the vacuum at this n
            double exponent = SubgroupExponent(lambda, m, -n);  // A(m - n sqrt(2)) = 2m - lambda n
            rows.Add((n, x, exponent, Math.Exp(exponent)));
        }
        return rows.ToArray();
    }

    /// <summary>The lambda that makes the subgroup exponent linear, i.e. 2*sqrt(2) - so that A(x) = 2x on the
    /// subgroup. Computed, and the residual of the linearity is measured rather than assumed.</summary>
    public static double SubgroupLambdaForLinearity() => 2.0 * Math.Sqrt(2.0);

