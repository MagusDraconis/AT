    // ===================== 4. THE RESIDUALS =====================

    /// <summary>
    /// THE COMPOSITION RESIDUAL, the audit's central measurement - and it is RELATIVE, which the first version got
    /// wrong: in the deep field both rates are tinier than any absolute tolerance, so the ABSOLUTE form
    /// |R(a+b) - R(a)R(b)| reported a free-room law as satisfying the constraint to 1.8E-001 while its log-additivity
    /// residual was 12.5. A multiplicative constraint must be measured against the size of its own factors.
    /// </summary>
    public static double CompositionResidual(ClockLaw law)
        => Pairs().Max(p => RelativeDeviation(Rate(law, p.A + p.B), Rate(law, p.A) * Rate(law, p.B)));

    /// <summary>The deviation of a product from its factors, measured against the size of the terms themselves.</summary>
    private static double RelativeDeviation(double actual, double expected)
    {
        double scale = Math.Max(Math.Abs(actual), Math.Abs(expected));
        return scale == 0.0 ? 0.0 : Math.Abs(actual - expected) / scale;
    }

    /// <summary>THE SAME EQUATION WRITTEN ON THE REDSHIFT FACTOR: the relative deviation of (1+z) from its factors.</summary>
    public static double RedshiftFactorResidual(ClockLaw law)
        => Pairs().Max(p => RelativeDeviation(OnePlusZ(law, p.A + p.B),
            OnePlusZ(law, p.A) * OnePlusZ(law, p.B)));

    /// <summary>THE SAME EQUATION WRITTEN ON THE METRIC MAGNITUDE: the relative deviation of F from its factors.</summary>
    public static double MetricResidual(ClockLaw law)
        => Pairs().Max(p => RelativeDeviation(law.F(p.A + p.B), law.F(p.A) * law.F(p.B)));

    /// <summary>THE SAME EQUATION WRITTEN ADDITIVELY: |ln R(a+b) - ln R(a) - ln R(b)|.</summary>
    public static double LogAdditivityResidual(ClockLaw law)
        => Pairs().Max(p => Math.Abs(Math.Log(Rate(law, p.A + p.B)) - Math.Log(Rate(law, p.A)) - Math.Log(Rate(law, p.B))));

    /// <summary>
    /// PATH INDEPENDENCE OF THE ACCUMULATED RATIO, measured on explicit routes: four decompositions of the SAME
    /// endpoint difference - one step, two steps, four steps and an irregular split - must give the same accumulated
    /// factor. A local rate gives the same total only when it is multiplicative, which is what this row measures
    /// rather than assumes. THE STEP VALUES ARE DELIBERATELY NOT MESH POINTS: the first version used 0.24, 0.12 and
    /// 0.06, which are all multiples of the audit's own mesh spacing, so the mesh interpolant passed this row too.
    /// </summary>
    public static double PathIndependenceResidual(ClockLaw law)
    {
        const double total = 0.2437;
        var routes = new[]
        {
            new[] { total },
            new[] { 0.1218, 0.1219 },
            new[] { 0.0609, 0.0609, 0.0609, 0.061 },
            new[] { 0.1037, 0.0701, 0.0699 },
        };
        var accumulated = routes.Select(r => r.Product(step => 1.0 / Rate(law, step))).ToArray();
        return RelativeDeviation(accumulated.Max(), accumulated.Min());
    }

    private static double Product(this IEnumerable<double> values, Func<double, double> selector)
    {
        double p = 1.0;
        foreach (var v in values) p *= selector(v);
        return p;
    }

    /// <summary>
    /// LOCALITY, measured rather than argued: the rate at a probe point is compared between two potential FIELDS that
    /// agree at the probe and differ in their gradients. Every law of the family is a function of the potential alone,
    /// so every residual is exactly zero - and the audit reports the residual's spread across the corpus, which is
    /// what makes the constraint non-selective rather than merely satisfied.
    /// </summary>
    public static double LocalityResidual(ClockLaw law)
    {
        // two configurations that AGREE at the probe and DIFFER in their gradients: a flat field and a ramp
        double[] flat = { -0.10, -0.10, -0.10 };
        double[] ramp = { -0.14, -0.10, -0.06 };
        const int probe = 1;
        double gradientFlat = Math.Abs(flat[probe] - flat[probe - 1]);
        double gradientRamp = Math.Abs(ramp[probe] - ramp[probe - 1]);
        // the two configurations differ in the gradient and not in the potential at the probe, so a LOCAL rate must
        // return the same number - and it does for every law, because the signature carries the potential alone
        return Math.Abs(Rate(law, flat[probe]) - Rate(law, ramp[probe])) + 0.0 * (gradientRamp - gradientFlat);
    }

    /// <summary>
    /// SYNCHRONIZATION TRANSITIVITY: if clock A agrees with B and B agrees with C, A agrees with C. Equality of rates
    /// is an equivalence relation for any function of the potential alone, so every residual is zero.
    /// </summary>
    public static double SynchronizationResidual(ClockLaw law)
    {
        double[] xs = { -0.30, -0.30, -0.05 };
        bool ab = Math.Abs(Rate(law, xs[0]) - Rate(law, xs[1])) < 1e-15;
        bool bc = Math.Abs(Rate(law, xs[1]) - Rate(law, xs[2])) < 1e-15;
        bool ac = Math.Abs(Rate(law, xs[0]) - Rate(law, xs[2])) < 1e-15;
        return (ab && bc && !ac) ? 1.0 : 0.0;
    }

    /// <summary>
    /// COUNT CONSERVATION, as the F-INDEPENDENCE of the residual rather than as a pass: the count is
    /// sum of rho over the cells, which contains no F at all, so the residual is the same number for every law and
    /// the SPREAD across the corpus is zero - the constraint constrains the density and not the clock.
    /// </summary>
    public static double CountConservationResidual(ClockLaw law)
    {
        double[] rho = { 0.4, 0.9, 1.0, 1.2, 2.0 };
        double total = rho.Sum();
        // the constraint is that the total is conserved under a flow that preserves each cell's occupancy count
        double[] after = rho.Select(r => r).ToArray();      // the flow the conservation statement is about
        return Math.Abs(total - after.Sum());
    }

    /// <summary>
    /// THE ACTUALIZATION COMPOSITION, TESTED AND REFUTED: if a combined system advances only when ALL its subsystems
    /// advance, its rate is the MINIMUM of theirs, while its occupancy multiplies. The audit measures the relative
    /// contradiction with each law's OWN rate at the combined density, so the row is law-level rather than a constant.
    /// </summary>
    public static double MinimumRuleContradiction(ClockLaw law)
    {
        double rho1 = 0.6, rho2 = 0.8;                  // two sub-vacuum subsystems: deepening potentials
        double x1 = Math.Log(rho1) / 3.0, x2 = Math.Log(rho2) / 3.0, combined = Math.Log(rho1 * rho2) / 3.0;
        double lawRate = Rate(law, combined);
        return lawRate == 0.0 ? double.PositiveInfinity
            : Math.Abs(Math.Min(Rate(law, x1), Rate(law, x2)) - lawRate) / lawRate;
    }

    /// <summary>
    /// THE COMPOSITION-RULE CENSUS, at the level of the RULE rather than of a law, and it is the measurement the
    /// actualization reading needs: with the occupancy MULTIPLYING, which combination of the parts' rates reproduces
    /// the whole's and which contradict it. The product rule is exact by construction; the minimum - which is what
    /// "all subsystems must advance" implies - and both means contradict the recorded rate by a measured amount.
    /// </summary>
    public static (string Rule, double R1, double R2, double CombinedDensity, double RuleValue, double PowerLawValue,
                   double Contradiction)[] CompositionRuleCensus()
    {
        double rho1 = 0.6, rho2 = 0.8;                     // two sub-vacuum subsystems: deepening potentials
        double combined = rho1 * rho2;                     // independent counts MULTIPLY
        const int d = 3;
        double powerLaw = Math.Pow(combined, 1.0 / d);     // the recorded rate, for comparison only
        var rows = new List<(string, double, double, double, double, double, double)>();
        foreach (var (rule, value) in new (string, double)[]
                 {
                     ("product", Math.Pow(rho1, 1.0 / 3.0) * Math.Pow(rho2, 1.0 / 3.0)),
                     ("minimum", Math.Min(Math.Pow(rho1, 1.0 / 3.0), Math.Pow(rho2, 1.0 / 3.0))),
                     ("arithmetic mean", 0.5 * (Math.Pow(rho1, 1.0 / 3.0) + Math.Pow(rho2, 1.0 / 3.0))),
                     ("geometric mean", Math.Sqrt(Math.Pow(rho1, 1.0 / 3.0) * Math.Pow(rho2, 1.0 / 3.0))),
                 })
            rows.Add((rule, Math.Pow(rho1, 1.0 / 3.0), Math.Pow(rho2, 1.0 / 3.0), combined, value, powerLaw,
                Math.Abs(value - powerLaw)));
        return rows.ToArray();
    }

    // ===================== 5. THE SELECTION TABLE =====================

    /// <summary>
    /// THE PINNED DATA, measured with a stencil FINE ENOUGH to resolve a mesh of the resolution this audit uses, so
    /// that a law is excluded by its own behaviour rather than by the step of the probe. The measured slope is the
    /// central difference at h = 1E-5, where a mesh of spacing 1E-2 contributes (pi h / delta)^2 - measured in the
    /// audit - rather than the modulation itself.
    /// </summary>
    public static double PinnedResidual(ClockLaw law)
    {
        const double h = 1.0e-5;
        double slope = (law.F(h) - law.F(-h)) / (2.0 * h);
        return Math.Abs(law.F(0.0) - 1.0) + Math.Abs(slope - 2.0);
    }

    /// <summary>The tolerances the two components of the conjunction are held to, stated rather than assumed.</summary>
    public const double CompositionTolerance = 1.0e-9;
    public const double PinnedTolerance = 1.0e-6;

    /// <summary>The conjunction, NORMALISED so that 1.0 is the boundary of both components at once.</summary>
    public static double ConjunctionResidual(ClockLaw law)
        => Math.Max(CompositionResidual(law) / CompositionTolerance, PinnedResidual(law) / PinnedTolerance);

    /// <summary>The tolerance each catalogue row is held to. The conjunction is normalised and the rest are not.</summary>
    public static double ToleranceOf(string constraint) => constraint switch
    {
        "composition AND the pinned data (the conjunction)" => 1.0,
        _ => SelectionTolerance,
    };

    /// <summary>The residual of one catalogue row for one law. Every row is measured - none is admitted on its name.</summary>
    public static double ResidualOf(string constraint, ClockLaw law) => constraint switch
    {
        "composition of successive redshifts" => CompositionResidual(law),
        "multiplicativity of the metric magnitude" => MetricResidual(law),
        "log-additivity of the rate" => LogAdditivityResidual(law),
        "path independence of the ACCUMULATED ratio" => PathIndependenceResidual(law),
        "operational clock transport consistency" => PathIndependenceResidual(law),
        "composition AND the pinned data (the conjunction)" => ConjunctionResidual(law),
        "locality" => LocalityResidual(law),
        "synchronization transitivity" => SynchronizationResidual(law),
        "count conservation" => CountConservationResidual(law),
        // the minimum rule is only on the table for laws that carry the pinned data: a law that does not is not an
        // admissible candidate for it, which is stated here rather than scored as a pass
        "actualization composition: all subsystems advance" =>
            PinnedResidual(law) > PinnedTolerance ? double.PositiveInfinity : MinimumRuleContradiction(law),
        _ => double.NaN,
    };

    /// <summary>The tolerance a residual is held to when a survivor is counted. Below this the equation holds to the
    /// arithmetic's own resolution, and the audit says which value it uses rather than treating a small number as
    /// zero.</summary>
    public const double SelectionTolerance = 1.0e-9;

    /// <summary>
    /// THE SELECTION TABLE: how many corpus laws satisfy each catalogue row, and whether the row discriminates AT ALL.
    /// A row whose residual is the SAME for every law is law-independent - satisfied by everything and therefore
    /// selecting nothing, however physically natural it sounds.
    /// </summary>
    public static (string Constraint, string Source, int Survivors, int Corpus, double Spread, double Tolerance, string Kind, string Presupposes)[]
        SelectionTable()
    {
        var corpus = Corpus();
        var rows = new List<(string, string, int, int, double, double, string, string)>();
        foreach (var c in Catalogue())
        {
            double tolerance = ToleranceOf(c.Name);
            var residuals = corpus.Select(l => ResidualOf(c.Name, l)).ToArray();
            bool anyFinite = residuals.Any(double.IsFinite);
            double spread = anyFinite ? residuals.Where(double.IsFinite).Max() - residuals.Where(double.IsFinite).Min() : 0.0;
            int survivors = residuals.Count(r => r <= tolerance);
            string kind = !anyFinite ? "REFUTED (no law passes)"
                : spread <= tolerance ? "NON-SELECTIVE (law-independent)"
                : survivors == corpus.Length ? "NON-SELECTIVE (all laws pass)"
                : survivors == 1 ? "SELECTS UNIQUELY"
                : survivors == 0 ? "REFUTED (no law passes)"
                : "PARTIAL";
            rows.Add((c.Name, c.Source, survivors, corpus.Length, spread, tolerance, kind, c.Presupposes));
        }
        return rows.ToArray();
    }

    /// <summary>
    /// THE EQUIVALENCE COLLAPSE, MEASURED: the four rows that come from different allowed sources - composition of
    /// successive redshifts, the group property written on the metric magnitude, log-additivity, and path
    /// independence of the accumulated ratio - have the SAME ZERO SET on the corpus. They are one equation in four
    /// languages, so the allowed source list is not four independent chances at a selector; it is one.
    /// </summary>
    public static (string Law, double Composition, double RedshiftFactor, double Metric, double LogAdditive,
                   double PathIndependence, bool SameZeroSet)[] EquivalenceCollapse()
        => Corpus().Select(l =>
        {
            double composition = CompositionResidual(l);
            double redshift = RedshiftFactorResidual(l);
            double metric = MetricResidual(l);
            double logarithmic = LogAdditivityResidual(l);
            double path = PathIndependenceResidual(l);
            bool sameZeroSet = new[] { composition, redshift, metric, logarithmic, path }
                .All(r => (r <= SelectionTolerance) == (composition <= SelectionTolerance));
            return (l.Name, composition, redshift, metric, logarithmic, path, sameZeroSet);
        }).ToArray();

    // ===================== 6. THE WEAKER SURVIVORS =====================

    /// <summary>
    /// APPROXIMATE MULTIPLICATIVITY LEAVES A CONTINUUM. The free-room law exp(2x + c x^2) has a composition residual
    /// |exp(-c a b) - 1|, so a tolerance eps admits every |c| below eps / max|ab| - an INTERVAL, not a point. Measured:
    /// the surviving interval and the redshift spread it implies at the target.
    /// </summary>
    public static (double Tolerance, double MaxC, double TargetSpread)[]
        ApproximateMultiplicativity()
    {
        double x = ClockLawUniquenessAudit.XTarget;
        return new[] { 1.0e-2, 1.0e-3, 1.0e-4, 1.0e-6 }.Select(eps =>
        {
            // BISECTED rather than derived: the interval's edge is measured on the residual the audit actually uses,
            // so the surviving interval and the tolerance cannot drift apart
            double low = 0.0, high = 10.0;
            for (int i = 0; i < 60; i++)
            {
                double mid = 0.5 * (low + high);
                if (CompositionResidual(ClockLawUniquenessAudit.FreeRoom(mid)) <= eps) low = mid; else high = mid;
            }
            double plus = OnePlusZ(ClockLawUniquenessAudit.FreeRoom(low), x);
            double minus = OnePlusZ(ClockLawUniquenessAudit.FreeRoom(-low), x);
            return (eps, low, Math.Abs(plus - minus));
        }).ToArray();
    }

    /// <summary>
    /// MULTIPLICATIVITY AT THE MESH: the interpolant agrees with exp(2x) at every mesh point, so every composition
    /// test with both arguments on the mesh passes EXACTLY, while the residual between mesh points is the modulation.
    /// The audit reports both numbers, because the difference between them is the whole result.
    /// </summary>
    public static (string Law, double OnTheMesh, double BetweenMesh, double MaxDeviation, double TargetShift)[]
        MeshMultiplication(double delta)
    {
        double x = ClockLawUniquenessAudit.XTarget;
        var mesh = MeshInterpolant(delta);
        var at = ClockLawUniquenessAudit.At();
        // mesh pairs: multiples of delta, so every argument and every sum is a mesh point
        int steps = (int)Math.Round(ClockLawUniquenessAudit.XPhysicalEnd / delta);
        double onMesh = 0.0;
        for (int i = 0; i < 200; i++)
        {
            double a = (steps + i) * delta, b = -i * delta;
            if (a + b < ClockLawUniquenessAudit.XPhysicalEnd) continue;
            onMesh = Math.Max(onMesh, Math.Abs(mesh.F(a + b) - mesh.F(a) * mesh.F(b)));
        }
        double maxDeviation = Enumerable.Range(0, 400)
            .Max(i => Math.Abs(mesh.F(-0.5 + (i + 0.37) * 0.5 / 400.0) / at.F(-0.5 + (i + 0.37) * 0.5 / 400.0) - 1.0));
        return new[]
        {
            (mesh.Name, onMesh, CompositionResidual(mesh), maxDeviation,
             Math.Abs(OnePlusZ(mesh, x) - OnePlusZ(at, x))),
        };
    }

    /// <summary>
    /// MULTIPLICATIVITY WITHOUT THE PINNED SLOPE LEAVES A ONE-PARAMETER FAMILY: exp(kx) is multiplicative for every
    /// k, so the constant is fixed by the pinned data and not by the structural constraint.
    /// </summary>
    public static (double K, double CompositionResidual, double OnePlusZAtTarget, bool CarriesThePinnedSlope)[]
        SlopeFamily()
        => new[] { 0.5, 1.0, 1.5, 2.0, 3.0 }.Select(k =>
        {
            var law = new ClockLaw($"exp({k:F1}x)", x => Math.Exp(k * x), "a multiplicative law with a free constant");
            return (k, CompositionResidual(law), OnePlusZ(law, ClockLawUniquenessAudit.XTarget),
                Math.Abs(k - 2.0) < 1e-12);
        }).ToArray();

