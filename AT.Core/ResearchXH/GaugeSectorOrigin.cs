/// reflection gives σ_z (isospin T3), the rotation generator gives σ_y, and their commutator gives σ_x
/// — exactly 3 generators (the weak sector). (3) SPECTRAL MODE CONNECTION — the octave families (3 of
/// them, QG138) form a natural 3D internal (color) space; su(3) on this space has 3²−1 = 8 generators
/// (the strong sector). (4) SYMMETRY-PRESERVING TRANSFORMATIONS — the gauge generators are the
/// automorphisms (r, s) and the doublet/family rotations they generate. (5) OCCUPATION-PRESERVING FLOWS —
