using System.Globalization;
using System.Text;
using AT.Tests.Shared;
using Xunit.Abstractions;

namespace AT.Tests.ResearchY.B_CircularGeometry;

/// <summary>
/// ResearchY-B_003 — Origin of 2π Audit test suite (Y_B_003_Tests.cs).
///
/// Question: can 2π emerge as a closure invariant without deriving π itself?
///
/// Verdict tested: 2π is EMERGENT in ROLE (the full-cycle period, an algebraic closure
/// invariant: R^N = identity, z_k^N = 1, θ_{k+N} ≡ θ_k) and BOUNDARY in VALUE
/// (2π = 2·π is transcendental, B_002). The radian normalization is a unit convention.
///
/// Deterministic: closed-form circulant eigenvalues + analytic roots of unity.
/// </summary>
public class Y_B_003_Tests : ResearchTestBase
{
    private const int N = 96;
    private const int K = 6;

    public Y_B_003_Tests(ITestOutputHelper output) : base(output) { }

    private static double Lambda(int k, int n = N)
        => 2.0 * Enumerable.Range(1, K).Sum(d => 1.0 - Math.Cos(2.0 * Math.PI * d * k / n));

    // ── [Required] Y_B_003_CycleClosure ──────────────────────────────────

    /// <summary>
    /// Cycle closure: the rotation R (one site) satisfies R^N = identity. N=96 is an
    /// exact integer; the cycle closes algebraically with no value of π.
    /// </summary>
    [Fact]
    public void Y_B_003_CycleClosure()
    {
        // The rotation by one site returns after N steps: (n + N) mod N = n.
        for (int n = 0; n < N; n++)
            Assert.Equal(n, (n + N) % N);

        // The cycle period in site steps is the integer N.
        Assert.Equal(96, N);
        Assert.True(N % 1 == 0);

        // Closure is exact (integer arithmetic) — no transcendental value enters.
        Assert.Equal(0, N % N);
    }

    // ── [Required] Y_B_003_PhasePeriodicity ──────────────────────────────

    /// <summary>
    /// The phase lattice θ_k = 2πk/N is periodic: θ_{k+N} ≡ θ_k (mod the full cycle).
    /// A minimal positive period exists (the full cycle); its radian value (2π) is the
    /// unit convention.
    /// </summary>
    [Fact]
    public void Y_B_003_PhasePeriodicity()
    {
        // Periodicity: the phase returns after N steps (sin/cos coincide).
        double theta5 = 2.0 * Math.PI * 5 / N;
        double theta5N = 2.0 * Math.PI * (5 + N) / N;
        Assert.Equal(Math.Cos(theta5), Math.Cos(theta5N), 10);
        Assert.Equal(Math.Sin(theta5), Math.Sin(theta5N), 10);

        // The full cycle exists: θ_N = 2π·N/N = 2π ≡ 0 (mod the cycle).
        Assert.Equal(2.0 * Math.PI, 2.0 * Math.PI * N / N, 12);

        // A minimal positive period exists structurally: sin is periodic.
        Assert.Equal(0.0, Math.Sin(2.0 * Math.PI), 12);
    }

    // ── [Required] Y_B_003_EigenmodeRotations ────────────────────────────

    /// <summary>
    /// The eigenmodes are roots of unity: under a one-site rotation the mode gains a
    /// phase factor z_k = e^{2πik/N}, and z_k^N = 1 (verified). The closure is the
    /// algebraic equation z^N = 1 — no value of π enters the content.
    /// </summary>
    [Fact]
    public void Y_B_003_EigenmodeRotations()
    {
        // z_k = e^{2πik/N}; z_k^N = 1 (root of unity, algebraic closure).
        // Verify via the real/imag parts: cos(2πk) = 1, sin(2πk) = 0.
        for (int k = 1; k <= 8; k++)
        {
            Assert.Equal(1.0, Math.Cos(2.0 * Math.PI * k), 10);
            Assert.Equal(0.0, Math.Sin(2.0 * Math.PI * k), 10);
        }

        // The phase factor per site: z_k = e^{2πik/N}, with |z_k| = 1 (unit modulus).
        // After N rotations the mode returns to itself: φ_k(n+N) = φ_k(n)·z_k^N = φ_k(n).
        // Verified via the periodicity of the harmonic (cos(2πk(n+N)/N) = cos(2πkn/N)).
        for (int n = 0; n < N; n += 7)
        {
            double c0 = Math.Cos(2.0 * Math.PI * 5 * n / N);
            double cN = Math.Cos(2.0 * Math.PI * 5 * (n + N) / N);
            Assert.Equal(c0, cN, 10);
        }
    }

    // ── [Required] Y_B_003_NSymmetry ─────────────────────────────────────

    /// <summary>
    /// The N=96 symmetry (dihedral D96) is generated by the rotation and a reflection.
    /// The rotation subgroup closes (R^N = identity); the cycle is invariant under the
    /// symmetry. All four mechanisms express the same algebraic closure.
    /// </summary>
    [Fact]
    public void Y_B_003_NSymmetry()
    {
        // The ring is regular (rotation symmetry): every site has degree 2K.
        Assert.Equal(12, 2 * K);

        // Z2 pairing — the ring symmetry in the spectrum (λ_k = λ_{N−k}).
        var lam = new double[N];
        for (int k = 0; k < N; k++) lam[k] = Lambda(k);
        int pairs = 0;
        for (int k = 1; k <= 47; k++)
            if (Math.Abs(lam[k] - lam[N - k]) < 1e-9) pairs++;
        Assert.Equal(47, pairs);

        // The cycle is invariant: rotating the phase lattice does not change its
        // period (θ_{k+s+N} ≡ θ_{k+s} for any shift s).
        for (int s = 1; s <= 6; s++)
        {
            double a = Math.Cos(2.0 * Math.PI * (s + 5) / N);
            double b = Math.Cos(2.0 * Math.PI * (s + 5 + N) / N);
            Assert.Equal(a, b, 10);
        }
    }

    // ── [Required] Y_B_003_Classification ────────────────────────────────

    /// <summary>
    /// 2π is EMERGENT in role (the full-cycle period, an algebraic closure invariant)
    /// and BOUNDARY in value (2π = 2·π is transcendental, B_002). The radian
    /// normalization is a unit convention, not a derivation.
    /// </summary>
    [Fact]
    public void Y_B_003_Classification()
    {
        // Role: the full cycle exists and is invariant (closure) — EMERGENT.
        // Verified by the algebraic closure statements (R^N=id, z^N=1, θ_{k+N}≡θ_k).

        // Value: 2π = 6.283185... is transcendental (twice π, B_002) — BOUNDARY.
        Assert.Equal(6.28319, 2.0 * Math.PI, 5);

        // The full cycle is NOT a fitted constant: it is forced by the finite closed
        // ring (no target, no selection).
        Assert.Equal(0, N % N); // closure is exact

        // Radian normalization is a convention: the full cycle in turns is 1; in
        // radians it is 2π. The cycle exists; the number is the unit choice.
        Assert.Equal(1.0, 2.0 * Math.PI / (2.0 * Math.PI), 12); // 1 full turn
    }

    // ── [Required] Y_B_003_Run ───────────────────────────────────────────

